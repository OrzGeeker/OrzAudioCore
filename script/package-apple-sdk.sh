#!/usr/bin/env bash
# Package the Apple SDK: an xcframework zip with metadata/licenses plus a
# generated SwiftPM binaryTarget Package.swift that references the zip checksum.
#
# Usage: package-apple-sdk.sh [output-dir] [--profile full|builtin-lite]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/.cmake-build/release"
PROFILE="full"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --profile) PROFILE="$2"; shift 2 ;;
    --*) echo "Unknown argument: $1" >&2; exit 2 ;;
    *) OUT="$1"; shift ;;
  esac
done

VERSION="$(node -p "require('$ROOT/decoder-manifest.json').sdkVersion")"
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
REPO_URL="${ORZ_RELEASE_BASE_URL:-https://github.com/OrzGeeker/OrzAudioCore/releases/download/v$VERSION}"
ASSET="OrzAudioCore-$VERSION-apple-$PROFILE.xcframework.zip"
STAGE="$OUT/OrzAudioCore-$VERSION-apple-$PROFILE"

"$ROOT/script/build-xcframework.sh" "$OUT/apple-$PROFILE" --profile "$PROFILE"
rm -rf "$STAGE"
mkdir -p "$STAGE" "$OUT"
cp -R "$OUT/apple-$PROFILE/OrzAudioCore.xcframework" "$STAGE/"
"$ROOT/script/collect-licenses.sh" "$STAGE/licenses" "$PROFILE"
cp "$ROOT/Docs/apple.md" "$STAGE/README.md"
node "$ROOT/script/generate-release-metadata.mjs" "$STAGE" --profile "$PROFILE" --platform apple

# SwiftPM expects the xcframework at the archive root; metadata and licenses
# travel next to it but do not interfere with binary target discovery.
rm -f "$OUT/$ASSET" "$OUT/$ASSET.sha256"
(cd "$STAGE" && ditto -c -k . "$OUT/$ASSET")
(cd "$OUT" && shasum -a 256 "$ASSET" > "$ASSET.sha256")
CHECKSUM="$(awk '{print $1}' "$OUT/$ASSET.sha256")"

cat > "$OUT/OrzAudioCore-$VERSION-apple-$PROFILE.swift" <<EOF
// Generated by script/package-apple-sdk.sh.
// swift-tools-version: 6.0
import PackageDescription

let package = Package(
    name: "OrzAudioCoreFull",
    platforms: [.iOS(.v15), .macOS(.v13)],
    products: [.library(name: "OrzAudioCore", targets: ["OrzAudioCore"])],
    targets: [
        .binaryTarget(
            name: "OrzAudioCore",
            url: "$REPO_URL/$ASSET",
            checksum: "$CHECKSUM"
        )
    ]
)
EOF
(cd "$OUT" && shasum -a 256 "OrzAudioCore-$VERSION-apple-$PROFILE.swift" > "OrzAudioCore-$VERSION-apple-$PROFILE.swift.sha256")

echo "$OUT/$ASSET"
echo "$OUT/OrzAudioCore-$VERSION-apple-$PROFILE.swift"
