import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PROFILE_IDS = Object.freeze({ 'builtin-lite': 0, full: 1, server: 2 });
export const PROFILES = Object.freeze(Object.keys(PROFILE_IDS));

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

export const repoRoot = root;

export function loadManifest(path = resolve(root, 'decoder-manifest.json')) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

export function formatsForProfile(manifest, profile) {
  if (!PROFILES.includes(profile)) throw new Error(`unknown profile: ${profile}`);
  return manifest.formats.filter(format => format.profiles.includes(profile));
}

export function decodersForProfile(manifest, profile) {
  const unique = new Map();
  for (const format of formatsForProfile(manifest, profile)) {
    unique.set(`${format.decoder}@${format.version}`, {
      id: format.decoder,
      version: format.version,
    });
  }
  return [...unique.values()].sort((a, b) => a.id.localeCompare(b.id));
}

/**
 * Cache namespaces must change whenever the binary's decoder set changes.
 * The hash covers both the exposed format ids and the decoder versions, so a
 * decoder patch or a profile change invalidates previously cached PCM.
 */
export function decoderSetHash(manifest, profile) {
  const payload = JSON.stringify({
    formats: formatsForProfile(manifest, profile).map(format => format.id),
    decoders: decodersForProfile(manifest, profile).map(decoder => `${decoder.id}@${decoder.version}`),
  });
  return createHash('sha256').update(payload).digest('hex').slice(0, 12);
}

export function cacheNamespace(manifest, profile) {
  return `orzaudio-${manifest.sdkVersion}-${profile}-${decoderSetHash(manifest, profile)}`;
}

/**
 * The runtime JSON returned by `orz_build_info()` and the artifact
 * `metadata/build-info.json` share this shape. Keep the key order stable: it
 * is part of the on-disk contract and is compared byte-for-byte in CI.
 */
export function buildInfo(manifest, profile) {
  return {
    sdk: 'OrzAudioCore',
    version: manifest.sdkVersion,
    abi: manifest.abiVersion,
    profile,
    fingerprint: cacheNamespace(manifest, profile),
    cacheNamespace: cacheNamespace(manifest, profile),
    formats: formatsForProfile(manifest, profile).map(format => format.id),
    decoders: decodersForProfile(manifest, profile),
  };
}

export function buildInfoJson(manifest, profile) {
  return JSON.stringify(buildInfo(manifest, profile));
}

export function generatedHeader(manifest) {
  const definitions = PROFILES.map(profile => {
    const id = PROFILE_IDS[profile];
    return [
      `#define ORZ_BUILD_INFO_PROFILE_${id} ${JSON.stringify(profile)}`,
      `#define ORZ_BUILD_INFO_JSON_${id} ${JSON.stringify(buildInfoJson(manifest, profile))}`,
    ].join('\n');
  }).join('\n');

  const selections = PROFILES.map((profile, index) => {
    const id = PROFILE_IDS[profile];
    return `${index === 0 ? '#if' : '#elif'} ORZ_PROFILE_ID == ${id}\n#define ORZ_BUILD_INFO_JSON ORZ_BUILD_INFO_JSON_${id}`;
  }).join('\n');

  return `/* Generated by script/generate-decoder-manifest.mjs. Do not edit. */
#ifndef ORZ_BUILD_INFO_GENERATED_H
#define ORZ_BUILD_INFO_GENERATED_H

#if !defined(ORZ_PROFILE_ID)
#define ORZ_PROFILE_ID 0
#endif

${definitions}

${selections}
#else
#error "Unsupported ORZ_PROFILE_ID; regenerate decoder-manifest outputs"
#endif

#endif
`;
}

export function kotlinManifest(manifest, profile = 'full') {
  const info = buildInfo(manifest, profile);
  const rows = formatsForProfile(manifest, profile).map(format =>
    `        DecoderFormatInfo("${format.id}", "${format.name}", "${format.decoder}", "${format.version}", "${format.category}", ${Boolean(format.seek)}, ${Boolean(format.subsong)})`
  ).join(',\n');
  return `// Generated by script/generate-decoder-manifest.mjs. Do not edit.
package com.orzgeeker.audiocore

object DecoderManifest {
    const val PROFILE = "${profile}"
    const val SDK_VERSION = "${manifest.sdkVersion}"
    const val ABI_VERSION = "${manifest.abiVersion}"
    const val CACHE_NAMESPACE = "${info.cacheNamespace}"

    val formats: List<DecoderFormatInfo> = listOf(
${rows}
    )

    val supportedIds: Set<String> = formats.map { it.id }.toSet()

    fun supports(format: String): Boolean = format.lowercase() in supportedIds
}
`;
}

export function sbom(manifest) {
  const packages = new Map();
  for (const format of manifest.formats) {
    const key = `${format.decoder}@${format.version}`;
    if (!packages.has(key)) packages.set(key, []);
    packages.get(key).push(format.id);
  }
  return {
    bomFormat: 'CycloneDX',
    specVersion: '1.5',
    version: 1,
    metadata: { component: { type: 'library', name: 'OrzAudioCore', version: manifest.sdkVersion } },
    components: [...packages.entries()].map(([key, formats]) => {
      const at = key.lastIndexOf('@');
      return {
        type: 'library',
        name: key.slice(0, at),
        version: key.slice(at + 1),
        properties: [{ name: 'orz:formats', value: formats.join(',') }],
      };
    }),
  };
}
