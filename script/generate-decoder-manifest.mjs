#!/usr/bin/env node
import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import {
  buildInfoJson,
  generatedHeader,
  kotlinManifest,
  loadManifest,
  repoRoot as root,
} from './lib/manifest.mjs';

const manifest = loadManifest(resolve(root, 'decoder-manifest.json'));
const symbol = {
  openmpt: 'decoder_openmpt',
  gme: 'decoder_gme',
  sidplayfp: 'decoder_sidplayfp',
  sc68: 'decoder_sc68',
  ym6: 'decoder_ym6',
  asap: 'decoder_asap',
  ahx2play: 'decoder_uade_ahx',
  midi: 'decoder_midi',
  v2m: 'decoder_v2m',
  soundmon: 'decoder_bp',
  adplug: 'decoder_adplug',
};
const quote = value => JSON.stringify(value);
const registry = manifest.formats.map(format => {
  const caps = format.seek || format.subsong ? 'NAV_CAPS' : 'BASE_CAPS';
  if (!symbol[format.decoder]) throw new Error(`No C decoder symbol for ${format.decoder}`);
  return `ENTRY(${quote(format.id)}, ${quote(format.name)}, ${quote(format.decoder)}, ${quote(format.version)}, ${quote(format.category)}, ${caps}, ${symbol[format.decoder]})`;
}).join(',\n') + '\n';
const registryOutput = resolve(root, 'Sources/OrzAudioKitCXX/dispatch/decoder_manifest.generated.inc');
const buildOutput = resolve(root, 'Sources/OrzAudioKitCXX/dispatch/build_info.generated.h');
const groups = { module: 'modules', console: 'retro', synth: 'synth' };
const browserManifest = `globalThis.ORZ_DECODER_FORMATS=${JSON.stringify(manifest.formats.map(format => ({ id: format.id, label: format.name, group: groups[format.category] ?? 'other' })))};\n`;
const browserOutput = resolve(root, 'Resources/Public/audio/decoder-manifest.generated.js');
const swiftManifest = `// Generated by script/generate-decoder-manifest.mjs. Do not edit.
public enum DecoderManifest {
    public static let sdkVersion = ${quote(manifest.sdkVersion)}
    public static let abiVersion = ${quote(manifest.abiVersion)}
    public static let decodableFormatIDs: Set<String> = [${manifest.formats.map(format => quote(format.id)).join(', ')}]
}
`;
const swiftOutput = resolve(root, 'Sources/OrzAudioKit/DecoderManifest.generated.swift');
const kotlinOutput = resolve(root, 'SDK/Android/audio-core/src/main/java/com/orzgeeker/audiocore/DecoderManifest.generated.kt');
const exists = async path => access(path).then(() => true, () => false);

const outputs = [
  [registryOutput, registry],
  [buildOutput, generatedHeader(manifest)],
  [swiftOutput, swiftManifest],
];
if (await exists(dirname(kotlinOutput))) outputs.push([kotlinOutput, kotlinManifest(manifest)]);

if (process.argv.includes('--check')) {
  for (const [path, expected] of outputs) {
    if (await readFile(path, 'utf8') !== expected) {
      throw new Error(`${path} is stale; run script/generate-decoder-manifest.mjs`);
    }
  }
  // The browser product projection belongs to OrzMusic, not the standalone
  // SDK. Validate it only when the consumer-owned output exists.
  if (await exists(browserOutput) && await readFile(browserOutput, 'utf8') !== browserManifest) {
    throw new Error('browser manifest is stale; run script/generate-decoder-manifest.mjs');
  }
  // Emit the per-profile JSON so callers can diff runtime build info in CI.
  console.log(JSON.stringify({
    version: manifest.sdkVersion,
    abi: manifest.abiVersion,
    profiles: Object.fromEntries(['builtin-lite', 'full', 'server'].map(profile => [profile, JSON.parse(buildInfoJson(manifest, profile))])),
  }));
} else {
  for (const [path, contents] of outputs) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, contents);
  }
  if (await exists(dirname(browserOutput))) await writeFile(browserOutput, browserManifest);
  const web = resolve(root, 'SDK/Web/decoder-manifest.json');
  await mkdir(dirname(web), { recursive: true });
  await writeFile(web, JSON.stringify(manifest, null, 2) + '\n');
}
